CREATE TABLE IF NOT EXISTS meetings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date DATE NOT NULL UNIQUE,
  meeting_type TEXT NOT NULL CHECK (meeting_type IN ('testimony', 'regular', 'stake', 'general')),
  presiding TEXT NOT NULL,
  conducting TEXT NOT NULL,
  announcements TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  opening_hymn JSONB NOT NULL CHECK (jsonb_typeof(opening_hymn) = 'object'),
  opening_prayer TEXT NOT NULL,
  ward_business JSONB NOT NULL CHECK (jsonb_typeof(ward_business) = 'array'),
  stake_business BOOLEAN NOT NULL DEFAULT FALSE,
  sacrament_hymn JSONB NOT NULL CHECK (jsonb_typeof(sacrament_hymn) = 'object'),
  speakers JSONB NOT NULL CHECK (jsonb_typeof(speakers) = 'array'),
  closing_hymn JSONB NOT NULL CHECK (jsonb_typeof(closing_hymn) = 'object'),
  closing_prayer TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS meetings_speakers_gin_idx
  ON meetings USING GIN (speakers jsonb_path_ops);
